// Turns the phone SPA in Figo/data/ into Figo/WebAssets.h: each asset gzipped at
// level 9 and written out as a C byte array, plus a source-hash ETag.
//
// The SPA is compiled INTO the firmware (it is only ~55KB gzipped), so an OTA
// update of Figo.ino.bin updates the page with it - no filesystem image, no
// version mismatch between the app and the page it serves.
//
// WebAssets.h is COMMITTED, so an Arduino IDE build from a fresh clone needs no
// Node. The price is a rule: after any edit to data/, run this. --check exits 1
// when the header is stale, so a forgotten regeneration can be caught before
// shipping the old page.
//
//   node tools/embed-spa/embed.mjs           # regenerate; exit 0
//   node tools/embed-spa/embed.mjs --check   # write nothing; exit 1 if stale
//
// No dependencies: zlib and crypto are built into Node.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync, constants } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const sketch = join(here, "..", "..");
const dataDir = join(sketch, "data");
const outPath = join(sketch, "WebAssets.h");

// [file in data/, C identifier stem]. Order is part of the hash.
const ASSETS = [
  ["index.html", "INDEX_HTML"],
  ["style.css", "STYLE_CSS"],
  ["app.js", "APP_JS"],
  ["update.html", "UPDATE_HTML"],
];
// Every listed asset is required: readFileSync throws on a missing one rather than
// quietly generating a header without it.

function sourceHash() {
  const h = createHash("sha256");
  for (const [name] of ASSETS) {
    h.update(name + "\0");
    h.update(readFileSync(join(dataDir, name)));
    h.update("\0");
  }
  return h.digest("hex");
}

function bytesToC(buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 16) {
    lines.push("  " + Array.from(buf.subarray(i, i + 16), (b) => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
  }
  return lines.join("\n");
}

function build() {
  const hash = sourceHash();
  const out = [];
  out.push(`// GENERATED by tools/embed-spa/embed.mjs from data/ - DO NOT EDIT.`);
  out.push(`// After any change under data/, run:  node tools/embed-spa/embed.mjs`);
  out.push(`// (--check exits 1 when this file is stale.)`);
  out.push(`// source-sha256: ${hash}`);
  out.push(`#ifndef WEB_ASSETS_H`);
  out.push(`#define WEB_ASSETS_H`);
  out.push(``);
  out.push(`#include <stddef.h>`);
  out.push(`#include <stdint.h>`);
  out.push(``);
  out.push(`// Strong validator for every asset below: the phone sends it back as If-None-Match`);
  out.push(`// and gets a 304 until the firmware (and so the page) changes.`);
  out.push(`#define WEB_ASSETS_ETAG "\\"${hash.slice(0, 16)}\\""`);
  out.push(``);
  for (const [name, id] of ASSETS) {
    const raw = readFileSync(join(dataDir, name));
    const gz = gzipSync(raw, { level: 9, memLevel: 9, strategy: constants.Z_DEFAULT_STRATEGY });
    gz[9] = 0xff; // gzip OS byte: zlib writes a per-platform value; pin it so output is reproducible
    out.push(`// ${name}: ${raw.length} bytes, ${gz.length} gzipped`);
    out.push(`static const uint8_t WEB_${id}_GZ[] = {`);
    out.push(bytesToC(gz));
    out.push(`};`);
    out.push(`static const size_t WEB_${id}_GZ_LEN = ${gz.length};`);
    out.push(``);
  }
  out.push(`#endif  // WEB_ASSETS_H`);
  out.push(``);
  return { text: out.join("\n"), hash };
}

const { text, hash } = build();

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  const m = current.match(/^\/\/ source-sha256: ([0-9a-f]{64})$/m);
  if (!m || m[1] !== hash) {
    console.error("WebAssets.h is STALE: data/ changed since it was generated.");
    console.error("Run:  node Figo/tools/embed-spa/embed.mjs   (then rebuild and flash)");
    process.exit(1);
  }
  console.log("WebAssets.h is up to date.");
  process.exit(0);
}

writeFileSync(outPath, text);
console.log(`wrote ${outPath} (${text.length} bytes of source, ${ASSETS.length} assets)`);
